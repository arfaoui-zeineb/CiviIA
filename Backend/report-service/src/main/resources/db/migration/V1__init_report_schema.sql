CREATE INDEX IF NOT EXISTS idx_report_equipment_id ON report(equipment_id);
CREATE INDEX IF NOT EXISTS idx_report_image_report_id ON report_image(report_id);
CREATE INDEX IF NOT EXISTS idx_report_history_report_id ON report_history(report_id, changed_at ASC);
CREATE INDEX IF NOT EXISTS idx_report_outbox_published ON report_outbox_event(published_at, created_at);

-- Trigger function: automatically insert into report_history on report creation or status change
CREATE OR REPLACE FUNCTION trg_report_history()
RETURNS TRIGGER AS $$
BEGIN
    IF (TG_OP = 'INSERT') THEN
        INSERT INTO report_history (report_id, old_status, new_status, changed_at)
        VALUES (NEW.id, NULL, NEW.status, COALESCE(NEW.created_at, now()));
        RETURN NEW;
    ELSIF (TG_OP = 'UPDATE') THEN
        IF (OLD.status IS DISTINCT FROM NEW.status) THEN
            INSERT INTO report_history (report_id, old_status, new_status, changed_at)
            VALUES (NEW.id, OLD.status, NEW.status, now());
        END IF;
        RETURN NEW;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_report_status_change ON report;
CREATE TRIGGER trg_report_status_change
AFTER INSERT OR UPDATE ON report
FOR EACH ROW
EXECUTE FUNCTION trg_report_history();
